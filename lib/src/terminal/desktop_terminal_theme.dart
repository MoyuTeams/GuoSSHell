/// 此映射不表示动态 OSC 颜色状态。
TerminalTheme themeForProfile(String scheme) {
  final theme = _profileThemes[scheme];
  if (theme == null) {
    throw ArgumentError.value(scheme, 'scheme', '不支持的终端静态配色');
  }
  return theme;
}

